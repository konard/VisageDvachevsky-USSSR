def create_app(config_name=None):
    """Application factory pattern"""

    app = Flask(__name__,
                template_folder='../frontend/templates',
                static_folder='../frontend/static')

    # Load configuration
    config = get_config(config_name)
    app.config.from_object(config)

    # Initialize extensions
    db.init_app(app)
    CORS(app, origins=app.config['CORS_ORIGINS'])
    jwt = JWTManager(app)
    bcrypt = Bcrypt(app)
    migrate = Migrate(app, db)

    # Initialize caching
    cache = Cache(app, config={
        'CACHE_TYPE': app.config['CACHE_TYPE'],
        'CACHE_DEFAULT_TIMEOUT': app.config['CACHE_DEFAULT_TIMEOUT']
    })

    # Initialize rate limiter
    limiter = Limiter(
        app=app,
        key_func=get_remote_address,
        storage_uri=app.config['RATELIMIT_STORAGE_URI'],
        strategy=app.config['RATELIMIT_STRATEGY'],
        default_limits=[app.config['RATELIMIT_DEFAULT']]
    )

    # Setup logging
    setup_logging(app)

    # Register blueprints
    app.register_blueprint(leaders_bp)
    app.register_blueprint(auth_bp)
    app.register_blueprint(analytics_bp)
    app.register_blueprint(content_bp)

    # Register error handlers
    register_error_handlers(app)

    # Register CLI commands
    register_cli_commands(app)

    # Main route
    @app.route('/')
    def index():
        """Render main page"""
        return render_template('index.html')

    # Video serving route
    @app.route('/videos/<path:filename>')
    def serve_video(filename):
        """Serve video files"""
        videos_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'videos')
        return send_from_directory(videos_dir, filename)

    @app.route('/api/videos/available')
    def get_available_videos():
        """Return list of video IDs that have a corresponding mp4 file in the videos/ directory."""
        videos_dir = os.path.join(os.path.dirname(os.path.dirname(__file__)), 'videos')
        available = []
        if os.path.isdir(videos_dir):
            for entry in os.listdir(videos_dir):
                if entry.lower().endswith('.mp4'):
                    stem = entry[:-4]
                    try:
                        available.append(int(stem))
                    except ValueError:
                        pass
        return jsonify({'available': sorted(available)})

    # Health check endpoint
    @app.route('/health')
    def health_check():
        """Health check endpoint for monitoring"""
        return jsonify({
            'status': 'healthy',
            'app': app.config['APP_NAME'],
            'version': app.config['APP_VERSION']
        }), 200

    # Create tables and initialize data
    with app.app_context():
        db.create_all()
        initialize_database(app)

    app.logger.info(f"{app.config['APP_NAME']} v{app.config['APP_VERSION']} started")

    return app


def setup_logging(app):
    """Configure comprehensive logging"""

    if not app.debug and not app.testing:
        # Create logs directory if it doesn't exist
        log_dir = os.path.dirname(app.config['LOG_FILE'])
        if not os.path.exists(log_dir):
            os.makedirs(log_dir)

        # File handler with rotation
        file_handler = RotatingFileHandler(
            app.config['LOG_FILE'],
            maxBytes=10240000,  # 10MB
            backupCount=10
        )
        file_handler.setFormatter(logging.Formatter(app.config['LOG_FORMAT']))
        file_handler.setLevel(logging.INFO)
        app.logger.addHandler(file_handler)

    # Console handler
    console_handler = logging.StreamHandler()
    console_handler.setFormatter(logging.Formatter(app.config['LOG_FORMAT']))
    console_handler.setLevel(logging.DEBUG if app.debug else logging.INFO)
    app.logger.addHandler(console_handler)

    app.logger.setLevel(getattr(logging, app.config['LOG_LEVEL']))
    app.logger.info('Logging configured')


def register_error_handlers(app):
    """Register custom error handlers"""

    @app.errorhandler(400)
    def bad_request(error):
        return jsonify({
            'success': False,
            'error': 'Bad request',
            'message': str(error)
        }), 400

    @app.errorhandler(401)
    def unauthorized(error):
        return jsonify({
            'success': False,
            'error': 'Unauthorized',
            'message': 'Authentication required'
        }), 401

    @app.errorhandler(403)
    def forbidden(error):
        return jsonify({
            'success': False,
            'error': 'Forbidden',
            'message': 'You do not have permission to access this resource'
        }), 403

    @app.errorhandler(404)
    def not_found(error):
        return jsonify({
            'success': False,
            'error': 'Not found',
            'message': 'Resource not found'
        }), 404

    @app.errorhandler(429)
    def rate_limit_exceeded(error):
        return jsonify({
            'success': False,
            'error': 'Rate limit exceeded',
            'message': 'Too many requests. Please try again later.'
        }), 429

    @app.errorhandler(500)
    def internal_error(error):
        app.logger.error(f'Internal server error: {error}')
        return jsonify({
            'success': False,
            'error': 'Internal server error',
            'message': 'An unexpected error occurred'
        }), 500


